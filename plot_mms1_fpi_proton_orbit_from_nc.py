#!/usr/bin/env python3
"""
plot_mms1_fpi_proton_orbit_from_nc.py
=====================================
Reads MMS FPI orbit and flux data from a NetCDF (.nc) file generated by
save_mms1_fpi_proton_orbit_nc.py, and visualizes polar orbit trajectories
colored by ion differential energy flux across all energy channels.

Key Features:
  1. Multi-Channel Grid View (--mode grid, default):
     - Displays all energy levels (e.g., 12 subplots in a 3x4 grid) side-by-side
       for instant cross-energy comparison.
     - Consistent color scaling and shared/individual colorbars.
  2. Single Channel View (--mode single --energy 1.821):
     - Generates a large, detailed publication-grade polar orbit plot for a specific energy.
  3. Presentation & Configuration:
     - Noon / Sun (12 LT) at Top by default (--noon top or --noon bottom).
     - Fully opaque flux points by default (--alpha 1.0, no transparency).
     - Adaptive or customizable point size (--point-size).
     - Earth boundary disk (R <= 1 R_E) and radial rings.

Author: Space Physics Pair-Programming Assistant
"""

import os
import argparse
import datetime
import warnings
warnings.filterwarnings('ignore')

import numpy as np

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import matplotlib.colors as mcolors

# Support both netCDF4 and scipy.io.netcdf fallback
try:
    import netCDF4 as nc
    HAS_NETCDF4 = True
except ImportError:
    from scipy.io import netcdf_file
    HAS_NETCDF4 = False


def read_mms_nc(nc_file_path):
    """
    Reads time, orbit coordinates, energies, and flux arrays from NetCDF.
    """
    if not os.path.exists(nc_file_path):
        raise FileNotFoundError(f"NetCDF file not found: {nc_file_path}")

    data = {}
    if HAS_NETCDF4:
        with nc.Dataset(nc_file_path, 'r') as ds:
            data['time'] = np.array(ds.variables['time'][:], dtype=np.float64)
            data['x'] = np.array(ds.variables['x'][:], dtype=np.float64)
            data['y'] = np.array(ds.variables['y'][:], dtype=np.float64)
            data['z'] = np.array(ds.variables['z'][:], dtype=np.float64)
            data['r'] = np.array(ds.variables['r'][:], dtype=np.float64)
            data['lt'] = np.array(ds.variables['lt'][:], dtype=np.float64)
            data['energy'] = np.array(ds.variables['energy'][:], dtype=np.float64)
            data['flux'] = np.array(ds.variables['flux'][:], dtype=np.float64)
            data['coord'] = getattr(ds, 'coordinate_system', 'GSE')
            data['probe'] = getattr(ds, 'spacecraft', 'MMS1')
    else:
        with netcdf_file(nc_file_path, 'r', mmap=False) as ds:
            data['time'] = np.array(ds.variables['time'][:], dtype=np.float64)
            data['x'] = np.array(ds.variables['x'][:], dtype=np.float64)
            data['y'] = np.array(ds.variables['y'][:], dtype=np.float64)
            data['z'] = np.array(ds.variables['z'][:], dtype=np.float64)
            data['r'] = np.array(ds.variables['r'][:], dtype=np.float64)
            data['lt'] = np.array(ds.variables['lt'][:], dtype=np.float64)
            data['energy'] = np.array(ds.variables['energy'][:], dtype=np.float64)
            data['flux'] = np.array(ds.variables['flux'][:], dtype=np.float64)
            data['coord'] = getattr(ds, 'coordinate_system', b'GSE')
            if isinstance(data['coord'], bytes):
                data['coord'] = data['coord'].decode('utf-8')
            data['probe'] = getattr(ds, 'spacecraft', b'MMS1')
            if isinstance(data['probe'], bytes):
                data['probe'] = data['probe'].decode('utf-8')

    return data


def setup_polar_axis(ax, noon_loc='top', coord='GSE', max_r=13.0):
    """
    Configures polar axis orientation, hour labels, and radial ticks.
    """
    noon_loc = noon_loc.lower()
    coord = coord.upper()

    if noon_loc == 'bottom':
        ax.set_theta_zero_location('N')
        ax.set_theta_direction(1)
        if coord == 'GSE':
            hour_labels = ['00 LT\n(Tail)', '03', '06 LT\n(Dawn)', '09',
                           '12 LT\n(Sun)', '15', '18 LT\n(Dusk)', '21']
        else:
            hour_labels = ['00 MLT', '03', '06 MLT', '09', '12 MLT', '15', '18 MLT', '21']
    else:
        # Standard View: 12 LT at Top, 00 LT at Bottom
        ax.set_theta_zero_location('S')
        ax.set_theta_direction(1) # CCW: 06 (Dawn) at Right, 18 (Dusk) at Left
        if coord == 'GSE':
            hour_labels = ['00 LT\n(Tail)', '03', '06 LT\n(Dawn)', '09',
                           '12 LT\n(Sun)', '15', '18 LT\n(Dusk)', '21']
        else:
            hour_labels = ['00 MLT', '03', '06 MLT', '09', '12 MLT', '15', '18 MLT', '21']

    # Radial ticks
    if max_r <= 14.0:
        r_lim = 13.0
        r_ticks = [3, 6, 9, 12]
    elif max_r <= 20.0:
        r_lim = float(np.ceil(max_r / 2.0) * 2.0)
        r_ticks = [4, 8, 12, 16]
    else:
        r_lim = float(np.ceil((max_r + 1.0) / 5.0) * 5.0)
        r_ticks = list(range(5, int(r_lim) + 1, 5))

    ax.set_ylim(0, r_lim)
    ax.set_yticks(r_ticks)
    ax.set_yticklabels([f'{r}' for r in r_ticks], fontsize=7, color='#555555')
    ax.set_rlabel_position(315)

    az_ticks = np.linspace(0, 2.0 * np.pi, 8, endpoint=False)
    ax.set_xticks(az_ticks)
    ax.set_xticklabels(hour_labels, fontsize=7.5, fontweight='bold')

    # Draw Earth center disk
    theta_earth = np.linspace(0, 2.0 * np.pi, 100)
    ax.fill(theta_earth, np.ones_like(theta_earth) * 1.0, color='#87CEEB', alpha=0.5, zorder=2)
    ax.plot(theta_earth, np.ones_like(theta_earth) * 1.0, color='#1E90FF', lw=1.0, zorder=2)

    ax.grid(True, color='gray', linestyle=':', alpha=0.5)
    return r_lim


def plot_grid(data, noon_loc='top', point_size=None, alpha=1.0, output_path='mms1_fpi_orbit_grid.png', dpi=300):
    """
    Plots a multi-panel grid comparing all energy channels on polar orbits.
    """
    t = data['time']
    r = data['r']
    lt = data['lt']
    energies = data['energy']
    flux = data['flux']
    coord = data.get('coord', 'GSE')
    probe = data.get('probe', 'MMS1')

    n_energies = len(energies)
    n_pts = len(lt)

    # Calculate grid geometry (e.g. 12 -> 3x4)
    if n_energies <= 4:
        ncols = n_energies
        nrows = 1
    elif n_energies <= 6:
        ncols = 3
        nrows = 2
    elif n_energies <= 8:
        ncols = 4
        nrows = 2
    elif n_energies <= 12:
        ncols = 4
        nrows = 3
    else:
        ncols = 4
        nrows = int(np.ceil(n_energies / 4.0))

    # Point size
    if point_size is not None:
        pt_size = point_size
    else:
        pt_size = 1.8 if n_pts <= 10000 else (1.0 if n_pts <= 30000 else 0.6)

    # Angular coordinate [radians]
    theta = lt * (2.0 * np.pi / 24.0)

    # Overall flux min/max for color scaling
    valid_all = flux[np.isfinite(flux) & (flux > 0)]
    if len(valid_all) > 0:
        cmin = max(1e3, 10.0 ** np.floor(np.log10(np.percentile(valid_all, 5))))
        cmax = min(1e9, 10.0 ** np.ceil(np.log10(np.percentile(valid_all, 98))))
    else:
        cmin, cmax = 1e4, 1e8

    norm = mcolors.LogNorm(vmin=cmin, vmax=cmax)
    cmap = plt.cm.turbo

    peak_r = float(np.nanmax(r)) if np.any(np.isfinite(r)) else 12.0

    # Date range string for title
    dt0 = datetime.datetime.fromtimestamp(t[0], tz=datetime.timezone.utc)
    dt1 = datetime.datetime.fromtimestamp(t[-1], tz=datetime.timezone.utc)
    date_str = dt0.strftime('%Y-%m-%d') if dt0.date() == dt1.date() else f"{dt0.strftime('%Y-%m-%d')} to {dt1.strftime('%Y-%m-%d')}"

    fig = plt.figure(figsize=(4.0 * ncols, 4.2 * nrows), dpi=dpi)
    fig.suptitle(f"{probe} FPI Ion Polar Orbit Trajectories ({coord})\nDate: {date_str} (Opacity α = {alpha})",
                 fontsize=14, fontweight='bold', y=0.98)

    last_sc = None
    for idx in range(n_energies):
        ax = fig.add_subplot(nrows, ncols, idx + 1, projection='polar')
        setup_polar_axis(ax, noon_loc=noon_loc, coord=coord, max_r=peak_r)

        # Orbit track underlay
        stride_trk = max(1, len(theta) // 3000)
        ax.plot(theta[::stride_trk], r[::stride_trk], color='#888888', lw=0.4, alpha=0.35, zorder=1)

        # Flux scatter
        e_val = energies[idx]
        fl_slice = flux[:, idx]

        last_sc = ax.scatter(theta, r, c=fl_slice, cmap=cmap, norm=norm,
                             s=pt_size, alpha=alpha, edgecolors='none', zorder=3,
                             rasterized=True)

        ax.set_title(f"Channel {idx+1:02d}: {e_val:.3f} keV", fontsize=10, fontweight='bold', pad=14)

    # Global shared colorbar at bottom
    fig.subplots_adjust(left=0.04, right=0.96, top=0.91, bottom=0.09, wspace=0.35, hspace=0.38)
    cbar_ax = fig.add_axes([0.25, 0.035, 0.50, 0.02])
    cbar = fig.colorbar(last_sc, cax=cbar_ax, orientation='horizontal')
    cbar.set_label('Differential Energy Flux [keV / (cm² s sr keV)]', fontsize=11, fontweight='bold')

    print(f"[Plotting] Saving grid figure to {output_path} (DPI={dpi})...")
    plt.savefig(output_path, dpi=dpi, bbox_inches='tight')
    plt.close(fig)
    print(f"[Plotting] Saved successfully: {output_path}")


def plot_single(data, target_energy_keV=1.821, noon_loc='top', point_size=None, alpha=1.0, output_path='mms1_fpi_orbit_single.png', dpi=300):
    """
    Plots a single large polar orbit trajectory for the chosen energy channel.
    """
    t = data['time']
    r = data['r']
    lt = data['lt']
    energies = data['energy']
    flux = data['flux']
    coord = data.get('coord', 'GSE')
    probe = data.get('probe', 'MMS1')

    # Find closest energy channel
    idx = int(np.argmin(np.abs(energies - target_energy_keV)))
    actual_energy = energies[idx]
    fl_slice = flux[:, idx]

    n_pts = len(lt)
    pt_size = point_size if point_size is not None else (3.0 if n_pts <= 5000 else (1.8 if n_pts <= 20000 else 1.0))

    theta = lt * (2.0 * np.pi / 24.0)

    valid = fl_slice[np.isfinite(fl_slice) & (fl_slice > 0)]
    if len(valid) > 0:
        cmin = max(1e3, 10.0 ** np.floor(np.log10(np.percentile(valid, 5))))
        cmax = min(1e9, 10.0 ** np.ceil(np.log10(np.percentile(valid, 98))))
    else:
        cmin, cmax = 1e4, 1e8

    norm = mcolors.LogNorm(vmin=cmin, vmax=cmax)
    cmap = plt.cm.turbo

    peak_r = float(np.nanmax(r)) if np.any(np.isfinite(r)) else 12.0

    dt0 = datetime.datetime.fromtimestamp(t[0], tz=datetime.timezone.utc)
    dt1 = datetime.datetime.fromtimestamp(t[-1], tz=datetime.timezone.utc)
    date_str = dt0.strftime('%Y-%m-%d') if dt0.date() == dt1.date() else f"{dt0.strftime('%Y-%m-%d')} to {dt1.strftime('%Y-%m-%d')}"

    fig = plt.figure(figsize=(9.0, 9.0), dpi=dpi)
    ax = fig.add_subplot(1, 1, 1, projection='polar')
    setup_polar_axis(ax, noon_loc=noon_loc, coord=coord, max_r=peak_r)

    # Orbit track underlay
    ax.plot(theta, r, color='#777777', lw=0.5, alpha=0.35, zorder=1, label='Orbit Track')

    # Scatter points with alpha (default 1.0, no transparency)
    sc = ax.scatter(theta, r, c=fl_slice, cmap=cmap, norm=norm,
                    s=pt_size, alpha=alpha, edgecolors='none', zorder=3,
                    rasterized=True, label=f'Flux @ {actual_energy:.3f} keV')

    # Start and End points
    ax.scatter(theta[0], r[0], marker='s', s=50, color='lime', edgecolors='black', lw=1.2, zorder=5, label='Start')
    ax.scatter(theta[-1], r[-1], marker='^', s=60, color='red', edgecolors='black', lw=1.2, zorder=5, label='End')

    title_text = f"{probe} Polar Orbit in {coord} (Energy: {actual_energy:.3f} keV)\nPeriod: {date_str} (Opacity α = {alpha})"
    ax.set_title(title_text, fontsize=12, fontweight='bold', pad=22)

    cbar = fig.colorbar(sc, ax=ax, pad=0.08, aspect=25, shrink=0.75)
    cbar.set_label(f'DEF @ ~{actual_energy:.3f} keV [keV/(cm² s sr keV)]', fontsize=10, fontweight='bold')
    ax.legend(loc='lower right', bbox_to_anchor=(1.25, -0.05), fontsize=8.5, framealpha=0.9)

    print(f"[Plotting] Saving single figure to {output_path} (DPI={dpi})...")
    plt.savefig(output_path, dpi=dpi, bbox_inches='tight')
    plt.close(fig)
    print(f"[Plotting] Saved successfully: {output_path}")


def main():
    parser = argparse.ArgumentParser(
        description="Plot MMS Polar Orbit Trajectories from NetCDF (.nc) file."
    )
    parser.add_argument('--input', '-i', type=str, required=True,
                        help="Path to input NetCDF (.nc) file.")
    parser.add_argument('--mode', type=str, default='grid', choices=['grid', 'single'],
                        help="Plot mode: 'grid' (all energy channels side-by-side, default) or 'single' (one energy).")
    parser.add_argument('--energy', type=float, default=1.821,
                        help="Target energy in keV for single mode (default: 1.821 keV).")
    parser.add_argument('--noon', type=str, default='top', choices=['top', 'bottom'],
                        help="Orientation of Sun/Noon (12 LT): 'top' (default) or 'bottom'.")
    parser.add_argument('--point-size', type=float, default=None,
                        help="Custom scatter point size (default: adaptive).")
    parser.add_argument('--alpha', type=float, default=1.0,
                        help="Opacity / alpha for flux points (default: 1.0, no transparency).")
    parser.add_argument('--output', '-o', type=str, default=None,
                        help="Output image file path (default: auto-generated based on input and mode).")
    parser.add_argument('--dpi', type=int, default=300,
                        help="Output image DPI (default: 300).")

    args = parser.parse_args()

    # Load NetCDF
    print(f"[Reader] Loading data from {args.input}...")
    data = read_mms_nc(args.input)
    print(f"[Reader] Loaded {len(data['time'])} timestamps, {len(data['energy'])} energy channels: {data['energy']}")

    # Determine output name if not specified
    base_name = os.path.splitext(os.path.basename(args.input))[0]
    if args.output is None:
        if args.mode == 'grid':
            out_file = f"{base_name}_grid.png"
        else:
            out_file = f"{base_name}_{args.energy:.3f}keV.png"
    else:
        out_file = args.output

    if args.mode == 'grid':
        plot_grid(
            data=data,
            noon_loc=args.noon,
            point_size=args.point_size,
            alpha=args.alpha,
            output_path=out_file,
            dpi=args.dpi
        )
    else:
        plot_single(
            data=data,
            target_energy_keV=args.energy,
            noon_loc=args.noon,
            point_size=args.point_size,
            alpha=args.alpha,
            output_path=out_file,
            dpi=args.dpi
        )


if __name__ == '__main__':
    main()

