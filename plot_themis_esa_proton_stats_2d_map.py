def read_stats_nc(nc_path):
    """
    Loads 2D/3D binned statistical variables and grid coordinates from the statistical NetCDF file.
    """
    if not os.path.exists(nc_path):
        raise FileNotFoundError(f"Statistical NetCDF file not found: {nc_path}")

    data = {}
    if HAS_NETCDF4:
        with nc.Dataset(nc_path, 'r') as ds:
            for vname in ds.variables:
                data[vname] = np.array(ds.variables[vname][:])
            data['probe'] = str(getattr(ds, 'spacecraft', 'THA'))
            data['coord'] = str(getattr(ds, 'coordinate_system', 'GSE'))
            data['dr'] = float(getattr(ds, 'dr_re', 0.5))
            data['dlon'] = float(getattr(ds, 'dlon_deg', 10.0))
            data['time_start'] = str(getattr(ds, 'time_coverage_start', ''))
            data['time_end'] = str(getattr(ds, 'time_coverage_end', ''))
    else:
        with netcdf_file(nc_path, 'r', mmap=False) as ds:
            for vname in ds.variables:
                data[vname] = np.array(ds.variables[vname][:])
            for attr, key, default in [
                ('spacecraft', 'probe', 'THA'),
                ('coordinate_system', 'coord', 'GSE'),
                ('time_coverage_start', 'time_start', ''),
                ('time_coverage_end', 'time_end', ''),
            ]:
                val = getattr(ds, attr, default)
                data[key] = val.decode('utf-8') if isinstance(val, bytes) else str(val)
            data['dr'] = float(getattr(ds, 'dr_re', 0.5))
            data['dlon'] = float(getattr(ds, 'dlon_deg', 10.0))

    return data


def setup_polar_axis(ax, noon_loc='top', coord='GSE', max_r=15.0):
    """
    Configures polar axis with Noon (12 LT) at top (or bottom), Earth disk at R <= 1 R_E,
    and clean radial/azimuthal grid lines.
    """
    noon_loc = noon_loc.lower()
    coord = coord.upper()

    if noon_loc == 'bottom':
        ax.set_theta_zero_location('N')
        ax.set_theta_direction(1)
    else:
        ax.set_theta_zero_location('S')
        ax.set_theta_direction(1)

    if coord == 'GSE':
        hour_labels = ['00 LT\n(Tail)', '03', '06 LT\n(Dawn)', '09',
                       '12 LT\n(Sun)', '15', '18 LT\n(Dusk)', '21']
    else:
        hour_labels = ['00 MLT', '03', '06 MLT', '09', '12 MLT', '15', '18 MLT', '21']

    if max_r <= 14.0:
        r_lim = 13.0
        r_ticks = [3, 6, 9, 12]
    elif max_r <= 20.0:
        r_lim = float(np.ceil(max_r / 2.0) * 2.0)
        r_ticks = list(range(4, int(r_lim) + 1, 4))
    else:
        r_lim = float(np.ceil(max_r / 5.0) * 5.0)
        r_ticks = list(range(5, int(r_lim) + 1, 5))

    ax.set_ylim(0, r_lim)
    ax.set_yticks(r_ticks)
    ax.set_yticklabels([f'{rt} $R_E$' for rt in r_ticks], fontsize=7, fontweight='bold', color='#111111',
                       bbox=dict(boxstyle='round,pad=0.15', facecolor='white', alpha=0.82, edgecolor='none'))
    ax.set_rlabel_position(315)
    for label in ax.get_yticklabels():
        label.set_zorder(15)

    az_ticks = np.linspace(0, 2.0 * np.pi, 8, endpoint=False)
    ax.set_xticks(az_ticks)
    ax.set_xticklabels(hour_labels, fontsize=7.5, fontweight='bold')

    theta_full = np.linspace(0, 2.0 * np.pi, 120)
    ax.fill(theta_full, np.ones_like(theta_full) * 1.0, color='#1b263b', alpha=0.85, zorder=8)
    theta_day = np.linspace(np.pi / 2.0, 1.5 * np.pi, 60)
    ax.fill(np.concatenate([[np.pi / 2.0], theta_day, [1.5 * np.pi]]),
            np.concatenate([[0.0], np.ones_like(theta_day), [0.0]]),
            color='#87CEEB', alpha=0.95, zorder=9)
    ax.plot(theta_full, np.ones_like(theta_full) * 1.0, color='#0077b6', lw=1.0, zorder=10)

    ax.grid(True, color='#444444', linestyle=':', linewidth=0.65, alpha=0.65, zorder=6)
    ax.set_axisbelow(False)
    ax.set_facecolor('#f8f9fa')
    return r_lim


def get_norm_and_cmap(arr, is_log=True, cmap_name='turbo', vmin=None, vmax=None):
    """
    Computes color normalization (LogNorm or Normalize) and colormap with clean NaN handling.
    """
    valid = arr[np.isfinite(arr) & (arr > 0 if is_log else True)]
    if len(valid) == 0:
        cmin = 1e3 if is_log else 0.0
        cmax = 1e8 if is_log else 1.0
    else:
        if is_log:
            cmin = vmin if vmin is not None else max(1e1, 10.0 ** np.floor(np.log10(np.percentile(valid, 3))))
            cmax = vmax if vmax is not None else min(1e10, 10.0 ** np.ceil(np.log10(np.percentile(valid, 98))))
            if cmax <= cmin:
                cmax = cmin * 10.0
        else:
            cmin = vmin if vmin is not None else float(np.percentile(valid, 2))
            cmax = vmax if vmax is not None else float(np.percentile(valid, 98))
            if cmax <= cmin:
                cmax = cmin + 1.0

    norm = mcolors.LogNorm(vmin=cmin, vmax=cmax) if is_log else mcolors.Normalize(vmin=cmin, vmax=cmax)
    cmap = plt.get_cmap(cmap_name).copy()
    cmap.set_bad(color='#f2f4f7', alpha=0.0)
    return norm, cmap


def format_period_str(data):
    t0 = data.get('time_start', '')[:10]
    t1 = data.get('time_end', '')[:10]
    if t0 and t1:
        return f"{t0} to {t1}" if t0 != t1 else t0
    return "Full Dataset"


def plot_2d_grid(data, metric='flux_mean', noon_loc='top', r_max=None, vmin=None, vmax=None,
                 output_path='tha_esa_stats_2d_grid.png', dpi=300):
    """
    Renders a multi-panel (e.g. 3x4) 2D polar map across all energy channels.
    """
    if metric not in data:
        raise KeyError(f"Metric '{metric}' not found in NetCDF file. Available: {list(METRIC_INFO.keys())}")

    arr = data[metric]
    energies = data['energy']
    r_edges = data['r_edges']
    lon_edges = data['lon_edges']
    theta_edges = np.deg2rad(lon_edges)

    probe = data.get('probe', 'THA')
    coord = data.get('coord', 'GSE')
    dr = data.get('dr', 0.5)
    dlon = data.get('dlon', 10.0)
    period_str = format_period_str(data)

    m_cfg = METRIC_INFO.get(metric, {'label': metric, 'short': metric, 'log': True, 'cmap': 'turbo'})
    norm, cmap = get_norm_and_cmap(arr, is_log=m_cfg['log'], cmap_name=m_cfg['cmap'], vmin=vmin, vmax=vmax)

    valid_r_mask = np.any(np.isfinite(arr) & (arr > 0), axis=(1, 2)) if arr.ndim == 3 else np.any(np.isfinite(arr) & (arr > 0), axis=1)
    max_data_r = float(r_edges[1:][valid_r_mask].max()) if np.any(valid_r_mask) else float(r_edges[-1])
    peak_r = r_max if r_max is not None else max_data_r

    if arr.ndim == 2:
        plot_2d_single(data, metric=metric, target_energy_keV=None, noon_loc=noon_loc,
                       r_max=peak_r, vmin=vmin, vmax=vmax, output_path=output_path, dpi=dpi)
        return

    n_energies = len(energies)
    if n_energies <= 4:
        ncols, nrows = n_energies, 1
    elif n_energies <= 6:
        ncols, nrows = 3, 2
    elif n_energies <= 8:
        ncols, nrows = 4, 2
    elif n_energies <= 12:
        ncols, nrows = 4, 3
    else:
        ncols = 4
        nrows = int(np.ceil(n_energies / 4.0))

    fig = plt.figure(figsize=(4.1 * ncols, 4.4 * nrows), dpi=dpi)
    fig.suptitle(
        f"{probe} ESA Ion 2D Spatial Distribution: {m_cfg['short']} ({coord})\n"
        f"Period: {period_str}  |  Bin Size: Δr = {dr:g} $R_E$, Δlon = {dlon:g}°",
        fontsize=14, fontweight='bold', y=0.985
    )

    Theta, R = np.meshgrid(theta_edges, r_edges)
    last_pcm = None

    for ie in range(n_energies):
        ax = fig.add_subplot(nrows, ncols, ie + 1, projection='polar')
        setup_polar_axis(ax, noon_loc=noon_loc, coord=coord, max_r=peak_r)

        slice_2d = np.ma.masked_invalid(arr[:, :, ie])
        if m_cfg['log']:
            slice_2d = np.ma.masked_where(slice_2d <= 0, slice_2d)

        last_pcm = ax.pcolormesh(Theta, R, slice_2d, cmap=cmap, norm=norm, shading='flat', zorder=1, rasterized=True)
        ax.set_title(f"Ch {ie+1:02d}: {energies[ie]:.3f} keV", fontsize=10.5, fontweight='bold', pad=13)

    fig.subplots_adjust(left=0.04, right=0.96, top=0.885, bottom=0.09, wspace=0.34, hspace=0.38)
    cbar_ax = fig.add_axes([0.24, 0.032, 0.52, 0.022])
    cbar = fig.colorbar(last_pcm, cax=cbar_ax, orientation='horizontal')
    cbar.set_label(m_cfg['label'], fontsize=11, fontweight='bold')

    print(f"[Plotter] Saving 2D grid map to {output_path} (DPI={dpi})...")
    plt.savefig(output_path, dpi=dpi, bbox_inches='tight')
    plt.close(fig)
    print(f"[Plotter] Saved successfully: {output_path}")


def plot_2d_single(data, metric='flux_mean', target_energy_keV=1.821, noon_loc='top',
                   r_max=None, vmin=None, vmax=None, output_path='tha_esa_stats_2d_single.png', dpi=300):
    """
    Renders a single large publication-grade 2D polar map for a selected energy channel (or 2D orbit metric).
    """
    if metric not in data:
        raise KeyError(f"Metric '{metric}' not found in NetCDF file. Available: {list(METRIC_INFO.keys())}")

    arr = data[metric]
    energies = data['energy']
    r_edges = data['r_edges']
    lon_edges = data['lon_edges']
    theta_edges = np.deg2rad(lon_edges)

    probe = data.get('probe', 'THA')
    coord = data.get('coord', 'GSE')
    dr = data.get('dr', 0.5)
    dlon = data.get('dlon', 10.0)
    period_str = format_period_str(data)

    m_cfg = METRIC_INFO.get(metric, {'label': metric, 'short': metric, 'log': True, 'cmap': 'turbo'})

    if arr.ndim == 3:
        e_target = target_energy_keV if target_energy_keV is not None else 1.821
        ie = int(np.argmin(np.abs(energies - e_target)))
        actual_e = energies[ie]
        slice_2d = arr[:, :, ie]
        energy_str = f"Energy: {actual_e:.3f} keV (Ch {ie+1:02d})"
    else:
        slice_2d = arr
        energy_str = "Spacecraft Orbit Coverage"

    valid_r_mask = np.any(np.isfinite(slice_2d) & (slice_2d > 0), axis=1)
    max_data_r = float(r_edges[1:][valid_r_mask].max()) if np.any(valid_r_mask) else float(r_edges[-1])
    peak_r = r_max if r_max is not None else max_data_r

    norm, cmap = get_norm_and_cmap(slice_2d, is_log=m_cfg['log'], cmap_name=m_cfg['cmap'], vmin=vmin, vmax=vmax)

    fig = plt.figure(figsize=(8.8, 8.8), dpi=dpi)
    ax = fig.add_subplot(1, 1, 1, projection='polar')
    setup_polar_axis(ax, noon_loc=noon_loc, coord=coord, max_r=peak_r)

    Theta, R = np.meshgrid(theta_edges, r_edges)
    masked_2d = np.ma.masked_invalid(slice_2d)
    if m_cfg['log']:
        masked_2d = np.ma.masked_where(masked_2d <= 0, masked_2d)

    pcm = ax.pcolormesh(Theta, R, masked_2d, cmap=cmap, norm=norm, shading='flat', zorder=1, rasterized=True)

    ax.set_title(
        f"{probe} 2D Spatial Map ({coord}) — {m_cfg['short']}\n"
        f"{energy_str}  |  Δr = {dr:g} $R_E$, Δlon = {dlon:g}°  |  {period_str}",
        fontsize=12, fontweight='bold', pad=22
    )

    cbar = fig.colorbar(pcm, ax=ax, pad=0.08, aspect=25, shrink=0.78)
    cbar.set_label(m_cfg['label'], fontsize=10.5, fontweight='bold')

    print(f"[Plotter] Saving single 2D map to {output_path} (DPI={dpi})...")
    plt.savefig(output_path, dpi=dpi, bbox_inches='tight')
    plt.close(fig)
    print(f"[Plotter] Saved successfully: {output_path}")


def plot_2d_summary(data, target_energy_keV=1.821, noon_loc='top', r_max=None,
                    output_path='tha_esa_stats_2d_summary.png', dpi=300):
    """
    Renders a 2x2 publication summary figure for a chosen energy channel:
      (a) Mean Differential Energy Flux (flux_mean)
      (b) Flux Standard Deviation (flux_std)
      (c) Geometric Mean Flux (flux_geom_mean)
      (d) Valid Sample Count (valid_count)
    """
    energies = data['energy']
    r_edges = data['r_edges']
    lon_edges = data['lon_edges']
    theta_edges = np.deg2rad(lon_edges)

    probe = data.get('probe', 'THA')
    coord = data.get('coord', 'GSE')
    dr = data.get('dr', 0.5)
    dlon = data.get('dlon', 10.0)
    period_str = format_period_str(data)

    ie = int(np.argmin(np.abs(energies - target_energy_keV)))
    actual_e = energies[ie]

    f_mean = data['flux_mean'][:, :, ie]
    f_std = data['flux_std'][:, :, ie]
    f_gmean = data['flux_geom_mean'][:, :, ie]
    v_cnt = data['valid_count'][:, :, ie].astype(np.float64)
    v_cnt[v_cnt <= 0] = np.nan

    valid_r_mask = np.any(np.isfinite(f_mean) & (f_mean > 0), axis=1)
    max_data_r = float(r_edges[1:][valid_r_mask].max()) if np.any(valid_r_mask) else float(r_edges[-1])
    peak_r = r_max if r_max is not None else max_data_r

    combined_flux = np.concatenate([
        f_mean[np.isfinite(f_mean) & (f_mean > 0)],
        f_std[np.isfinite(f_std) & (f_std > 0)],
        f_gmean[np.isfinite(f_gmean) & (f_gmean > 0)]
    ])
    norm_flux, cmap_flux = get_norm_and_cmap(combined_flux, is_log=True, cmap_name='turbo')
    norm_cnt, cmap_cnt = get_norm_and_cmap(v_cnt, is_log=True, cmap_name='viridis')

    panels = [
        ('(a) Mean Flux (μ)', f_mean, norm_flux, cmap_flux, 'DEF [keV/(cm² s sr keV)]'),
        ('(b) Standard Deviation (σ)', f_std, norm_flux, cmap_flux, 'DEF [keV/(cm² s sr keV)]'),
        ('(c) Geometric Mean Flux', f_gmean, norm_flux, cmap_flux, 'DEF [keV/(cm² s sr keV)]'),
        ('(d) Valid Sample Count (N)', v_cnt, norm_cnt, cmap_cnt, 'Valid Samples per Bin [counts]'),
    ]

    fig = plt.figure(figsize=(12.5, 11.8), dpi=dpi)
    fig.suptitle(
        f"{probe} ESA Statistical Summary @ {actual_e:.3f} keV ({coord})\n"
        f"Period: {period_str}  |  Grid: Δr = {dr:g} $R_E$, Δlon = {dlon:g}°",
        fontsize=14, fontweight='bold', y=0.985
    )

    Theta, R = np.meshgrid(theta_edges, r_edges)

    for idx, (title, arr2d, norm, cmap, clabel) in enumerate(panels):
        ax = fig.add_subplot(2, 2, idx + 1, projection='polar')
        setup_polar_axis(ax, noon_loc=noon_loc, coord=coord, max_r=peak_r)

        m2d = np.ma.masked_where((~np.isfinite(arr2d)) | (arr2d <= 0), arr2d)
        pcm = ax.pcolormesh(Theta, R, m2d, cmap=cmap, norm=norm, shading='flat', zorder=1, rasterized=True)
        ax.set_title(title, fontsize=11.5, fontweight='bold', pad=15)

        cbar = fig.colorbar(pcm, ax=ax, pad=0.09, aspect=22, shrink=0.78)
        cbar.set_label(clabel, fontsize=9.5, fontweight='bold')

    fig.subplots_adjust(left=0.05, right=0.95, top=0.89, bottom=0.05, wspace=0.32, hspace=0.30)

    print(f"[Plotter] Saving 4-panel publication summary to {output_path} (DPI={dpi})...")
    plt.savefig(output_path, dpi=dpi, bbox_inches='tight')
    plt.close(fig)
    print(f"[Plotter] Saved successfully: {output_path}")


