    if args.output is None:
        if mode == 'grid':
            out_path = f"{base_name}_{args.metric}_2d_grid.png"
        elif mode == 'summary':
            out_path = f"{base_name}_{target_energy:.3f}keV_2d_summary.png"
        else:
            out_path = f"{base_name}_{args.metric}_{target_energy:.3f}keV_2d_map.png"
    else:
        out_path = args.output

